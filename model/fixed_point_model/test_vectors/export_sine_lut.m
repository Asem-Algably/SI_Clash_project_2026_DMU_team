% Export the quarter-wave sine LUT as SystemVerilog (Q1.15 for lut_rom.sv).
%
% Robust: searches for get_hw_config.m in multiple candidate folders.
% Works no matter where you placed the config file.
%
% Output: <folder of this script>/generated/sine_quarter_lut.svh

function export_sine_lut(out_path)
    this_dir = fileparts(mfilename('fullpath'));   % folder of this script

    % ---------------------------------------------------------------
    % 1. Find get_hw_config.m — search in several candidate locations
    % ---------------------------------------------------------------
    candidates = { ...
        fullfile(this_dir, 'config'), ...                         % config/ subfolder
        this_dir, ...                                              % same folder as script
        fullfile(this_dir, '..', 'config'), ...                   % parent/config
        fullfile(this_dir, '..', 'fixed_point_model', 'config'), ...% sibling project
        fullfile(this_dir, '..', 'fixed_point_model'), ...         % sibling flat
    };

    cfg_dir = '';
    for k = 1:numel(candidates)
        if exist(fullfile(candidates{k}, 'get_hw_config.m'), 'file')
            cfg_dir = candidates{k};
            break;
        end
    end

    if isempty(cfg_dir)
        fprintf('\n❌ ERROR: get_hw_config.m not found. Searched:\n');
        for k = 1:numel(candidates)
            fprintf('   %s\n', candidates{k});
        end
        fprintf('\n✅ FIX (pick one):\n');
        fprintf('   A) Move get_hw_config.m to:  %s\\config\\\n', this_dir);
        fprintf('   B) Keep it in:              %s\\\n', this_dir);
        fprintf('\nThen re-run: export_sine_lut\n\n');
        error('get_hw_config.m not found');
    end

    addpath(cfg_dir);
    fprintf('✓ Using config from: %s\n', cfg_dir);

    % ---------------------------------------------------------------
    % 2. Output folder: <this_dir>/generated/
    % ---------------------------------------------------------------
    gen_dir = fullfile(this_dir, 'generated');
    if ~exist(gen_dir, 'dir')
        mkdir(gen_dir);
        fprintf('✓ Created: %s\n', gen_dir);
    end

    if nargin < 1 || isempty(out_path)
        out_path = fullfile(gen_dir, 'sine_quarter_lut.svh');
    end

    % Make sure parent folder exists
    out_parent = fileparts(out_path);
    if ~isempty(out_parent) && ~exist(out_parent, 'dir')
        mkdir(out_parent);
    end

    % ---------------------------------------------------------------
    % 3. Load LUT and write .svh
    % ---------------------------------------------------------------
    cfg = get_hw_config();
    lut_fi     = cfg.derot.lut;
    N_entries  = numel(lut_fi);
    PHASE_BITS = cfg.derot.addr_bits;
    DATA_WIDTH = 16;
    assert(PHASE_BITS == 12, 'LUT export expects addr_bits = 12');

    try
        stored = double(storedInteger(lut_fi));
    catch
        stored = round(double(lut_fi) * 2^16);
    end
    lut_q15 = max(0, min(32767, round(stored / 2)));

    fid = fopen(out_path, 'w');
    if fid <= 0
        error('Cannot write to %s (check folder permissions)', out_path);
    end
    fprintf(fid, '// Auto-generated by export_sine_lut.m — do not edit\n');
    fprintf(fid, '// Quarter-wave sine LUT, Q1.15, midpoint sampled, 4096 entries\n');
    fprintf(fid, '// S[a] = sin((a + 0.5) * (pi/2) / 4096) * 32767\n');
    for k = 1:N_entries
        fprintf(fid, "%d'd%d: v = %d'd%d;\n", ...
                PHASE_BITS, k-1, DATA_WIDTH, lut_q15(k));
    end
    fclose(fid);

    % ---------------------------------------------------------------
    % 4. Report
    % ---------------------------------------------------------------
    fprintf('\n==========================================================\n');
    fprintf('✓ Wrote: %s\n', out_path);
    fprintf('  %d entries\n', N_entries);
    fprintf('==========================================================\n');
    fprintf('Sanity check (Q1.15):\n');
    for a = [0, 1024, 2047, 2048, 3072, 4095]
        fprintf('  S[%4d] = %5d (0x%04X)\n', a, lut_q15(a+1), lut_q15(a+1));
    end
    fprintf('\nExpected: ~3, ~12540, ~23170, ~23171, ~30292, 32767\n');
    fprintf('\nNext step: copy this file to your RTL folder:\n');
    fprintf('  %s\n', out_path);
    fprintf('  →  <your_rtl_folder>/sine_quarter_lut.svh\n');
    fprintf('==========================================================\n\n');
end